    def binary_search(self, func, bounds, search_parameter,
                      tol=10**-10, depth=0, negative=True,
                      max_depth=25, log=True, left=None, right=None, **kwargs):

        if depth == 0:
            left = func(bounds[0], **kwargs) if not negative else func(-bounds[0], **kwargs)
            right = func(bounds[1], **kwargs) if not negative else func(-bounds[1], **kwargs)

        middle = (bounds[0] + bounds[1])/2 if not log else 10**((log10(bounds[0]) + log10(bounds[1]))/2)
        middle = -middle if negative else middle
        middle_value = func(middle, **kwargs)
        if abs(middle_value - search_parameter) <= tol:
            return middle

        if depth > max_depth:
            #print('did not converge, minimum error is', abs(middle_value - search_parameter))
            raise Exception('did not converge')
            return middle
        if left< search_parameter < middle_value:
            return self.binary_search(func, [bounds[0], abs(middle)], search_parameter, tol=tol,
                                      depth=depth+1, negative=negative, max_depth=max_depth,
                                      log=log, left=left, right=middle_value, **kwargs)
        elif middle_value < search_parameter < right:
            return self.binary_search(func, [abs(middle), bounds[1]], search_parameter, tol=tol,
                                      depth=depth+1, negative=negative, max_depth=max_depth,
                                      log=log, left=middle_value, right=right, **kwargs)
        else:
            #print('did not converge, minimum error is', abs(middle_value - search_parameter))
            raise Exception('did not converge')
            return middle

    def minimize_by_search(self, func, bounds, tol=10**-10,
                           depth=0, negative=True, breadth=10, first_breadth=None,
                           max_depth=25, nearest_value_tie_breaker=None,
                           log=True, parallel=True,previuos_results={},
                           precesion=0, old_xs=[], old_ys=[],silent=False,**kwargs):
        ''' tolerance is the minimum error that is acceptable
            precesion is the acceptable difference between the bounds

            returns the x that gives the minimum y, and all the computed points
        '''
        def inner_func(x, **kwargs):
            if x in previuos_results:
                return previuos_results[x]
            else:
                return func(x, **kwargs)

        inner_breadth = breadth
        if (depth == 0) and first_breadth is not None: inner_breadth = first_breadth

        if parallel: parallel=-1
        else: parallel=1
        if log:
            xs = np.linspace(log10(abs(bounds[0])), log10(abs(bounds[1])), inner_breadth)
            xs = 10**xs
        else:
            xs = np.linspace(abs(bounds[0]), abs(bounds[1]), inner_breadth)
        if negative: xs = -xs

        xs = np.array([x for x in xs if not np.isnan(x)])
        xs = sorted(xs)

        ys = Parallel(n_jobs=parallel, verbose=0)(delayed(inner_func)(x, **kwargs) for x in xs)
        previuos_results = {x:y for x,y in zip(xs, ys)}
        #ys = [func(x, **kwargs) for x in xs]
        #check if there is more than one minimum
        if nearest_value_tie_breaker is not None:
            minimas = [i for i in range(len(ys)) if ys[i] == min(ys)]
            minimum_i = minimas[np.argmin([abs(xs[i]-nearest_value_tie_breaker) for i in minimas])]
            x = xs[minimum_i]

        else:
            x = xs[np.argmin(ys)]
            minimum_i = np.argmin(ys)

        old_xs.extend(xs)
        old_ys.extend(ys)

        if min(ys) <= tol:
            return x, [old_xs, old_ys]
        if abs(abs(min(xs)) - abs(max(xs))) <= precesion:
            return x, [old_xs, old_ys]
        if len(set(ys)) == 1:
            return x, [old_xs, old_ys]
        if depth > max_depth:
            return x, [old_xs, old_ys]

        if minimum_i == 0:
            l_boundary = xs[0]
            r_boundary = xs[1]
        else:
            new_lower = minimum_i - 1 if minimum_i - 1 >= 0 else 0
            new_upper = minimum_i + 1 if minimum_i + 1 < len(xs) else - 1
            l_boundary = xs[new_lower]
            r_boundary = xs[new_upper]
        if not silent: print('Searching between l_boundary:', l_boundary, 'r_boundary:', r_boundary)
        return self.minimize_by_search(func, [l_boundary, r_boundary], tol, depth=depth+1,
                                       negative=negative, breadth=breadth, max_depth=max_depth,
                                       nearest_value_tie_breaker=nearest_value_tie_breaker,
                                       parallel=parallel, log=log,
                                       previuos_results=previuos_results,
                                       precesion=precesion, old_xs=old_xs, old_ys=old_ys,
                                       silent=silent,**kwargs)
