    def get_sub_rate_exact(self, point):
        '''command format: wfes_single --fixation -N [pop_size] -s [selection_coeff] -v [mue_frwrd] -u [mue_bckwrds] -h 0.5
        '''
        command = f'{wfes_single} --fixation -N {point.pop_size} -s {point.selection_coeff*2} \
                    -v {point.mue_frwrd} -u {point.mue_bckwrds} -h 0.5'

        process = subprocess.Popen(command.split(), stdout=subprocess.PIPE)
        output, error = process.communicate()
        output = output.decode()
        lines = output.split('\n')
        time = np.inf
        for line in lines:
            if 'T_fix' in line:
                time = float(line.split('=')[1].strip())
        if time == np.inf:
            return np.inf
        return 1/(time)

