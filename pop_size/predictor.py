    def get_sub_rate_regression(self, point, interpolate=True, test=False):
        '''get the sub rate using the linear regression
        '''
        def regression_sub(point, selection=None):
            if selection is None: selection = point.selection_coeff
            a, b = per_selection_linear_regression[selection]
            log_subrate = a*np.log10(point.mue_frwrd) + b
            return 10**log_subrate

        if not self.per_pop_linear_regression:
            raise Exception('fit the linear regression first')

        if point.pop_size not in self.per_pop_linear_regression:
            extra_points = self.get_train_points(num=20, popsize_range=[point.pop_size, point.pop_size], negative=False)
            self.fit_per_selection_linear_regression(extra_points)

        per_selection_linear_regression = self.per_pop_linear_regression[point.pop_size]

        def regression_sub(point, selection=None):
            if selection is None: selection = point.selection_coeff
            a, b = per_selection_linear_regression[selection]
            log_subrate = a*np.log10(point.mue_frwrd) + b
            return 10**log_subrate

        selections = [float(x) for x in per_selection_linear_regression.keys()]

        if test and point.selection_coeff in selections:
            #remove the point from the list
            selections.remove(point.selection_coeff)

        if point.selection_coeff < min(selections): return 0
        elif point.selection_coeff > max(selections): return regression_sub(point, max(selections))
        elif point.selection_coeff in selections: return regression_sub(point)

        if point.selection_coeff not in selections:

            if not interpolate:
                min_diff = np.inf
                for selection in selections:
                    if abs(selection - point.selection_coeff) < min_diff:
                        min_diff = abs(selection - point.selection_coeff)
                        most_similar_selection = selection
                return regression_sub(point, most_similar_selection)

            if point.selection_coeff <= min(selections):
                return regression_sub(point, min(selections))

            elif point.selection_coeff >= max(selections):
                return regression_sub(point, max(selections))

            upper = min([x for x in selections if x > point.selection_coeff])
            lower = max([x for x in selections if x < point.selection_coeff])


            subh = np.log10(regression_sub(point, upper))
            subl = np.log10(regression_sub(point, lower))

            #y = y1 + (x-x1)*(y2-y1)/(x2-x1)
            value = subl + (point.selection_coeff - lower)*(subh-subl)/(upper-lower)

            return 10**value

