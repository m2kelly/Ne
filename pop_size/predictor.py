    def get_sub_rate_diffusion_prob_hit(self, point):
        # inner functions
        def psi(mu, sigma, u1, u2):
            """
            ψ(μ) = exp(-2 σ μ) * μ^{-2u1} * (1-μ)^{-2u2}
            """
            # Avoid singularities at endpoints
            if mu <= 0.0:
                return 0.0
            if mu >= 1.0:
                return 0.0

            return (
                np.exp(-2.0 * sigma * mu)
                * (mu ** (-2.0 * u1))
                * ((1.0 - mu) ** (-2.0 * u2))
            )

        def phi(x, sigma, u1, u2):
            """
            φ(x) = ∫0^x ψ(μ)dμ / ∫0^1 ψ(μ)dμ
            """
            num, _ = I(psi, 0.0, x, args=(sigma, u1, u2))
            den, _ = I(psi, 0.0, 1.0, args=(sigma, u1, u2))
            return num / den

        def phi_prime(x, sigma, u1, u2):
            """
            φ'(x) = ψ(x) / ∫0^1 ψ(μ)dμ
            """
            den, _ = I(psi, 0.0, 1.0, args=(sigma, u1, u2))
            return psi(x, sigma, u1, u2) / den

        def green(x, y, sigma, u1, u2):
            """
            Killed Green function for absorption at 0 or 1. 
            """
            if y <= 0.0 or y >= 1.0:
                return 0.0

            g2 = y * (1.0 - y)
            phix = phi(x, sigma, u1, u2)
            phiy = phi(y, sigma, u1, u2)
            phipy = phi_prime(y, sigma, u1, u2)

            if x < y:
                return 2.0 * phix * (1.0 - phiy) / (g2 * phipy)
            else:
                return 2.0 * (1.0 - phix) * phiy / (g2 * phipy)

        def alpha(x, sigma, u1, u2):
            """
            α(x) = ∫0^1 G(x,y)dy
            Mean absorption time in diffusion units.
            """
            eps = 1e-12

            left, _ = I(
                lambda y: green(x, y, sigma, u1, u2),
                eps,
                x,
            )

            right, _ = I(
                lambda y: green(x, y, sigma, u1, u2),
                x,
                1.0 - eps,
            )

            return left + right

        mu_f = point.mue_frwrd
        mu_b = point.mue_bckwrds
        N = point.pop_size

        M = 2.0 * N

        sigma = M * point.selection_coeff
        u1 = M * mu_f
        u2 = M * mu_b

        x0 = 1.0 / M

        phi_x0 = phi(x0, sigma, u1, u2)
        alpha_x0 = alpha(x0, sigma, u1, u2)

        # Mean waiting time for first mutation in generations:
        # 1 / (M * mu_f)
        #
        # Mean segregating time in generations:
        # M * alpha_x0
        #
        # Substitution rate per generation:
        sub_rate = phi_x0 / ((1.0 / (M * mu_f)) + (M * alpha_x0))
        return sub_rate
            
    
    
       
